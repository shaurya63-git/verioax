from pathlib import Path

import streamlit as st

import results
import ui
from client import ClientError
from state import client, ocr_available
from trustguard.schemas import AnalysisMode

MODES = {AnalysisMode.FULL: "Full security analysis", AnalysisMode.SCAM: "Scam & hoax only", AnalysisMode.PII: "Personal data only"}
SAMPLE_DIR = Path(__file__).resolve().parents[2] / "samples"          # synthetic files, generated by scripts/make_samples.py
SAMPLES = {"KYC phishing email (PDF)": "kyc_phishing_email.pdf", "Forwarded messages (Word)": "forwarded_messages.docx",
           "SMS screenshot (image, OCR)": "challan_sms_screenshot.png"}
SAMPLES = {label: name for label, name in SAMPLES.items() if (SAMPLE_DIR / name).is_file()}

ui.page_header("File scanner", "Upload a document or a screenshot. TrustGuard extracts the text, finds and removes personal data, "
                               "and checks the content and its links for scams.")

with st.container(border=True):
    pick = st.pills("Try a sample file", list(SAMPLES), key="file_sample") if SAMPLES else None
    up = st.file_uploader("File", type=["pdf", "docx", "txt", "csv", "png", "jpg", "jpeg"], key="file_up",
                          help="PDF, DOCX, TXT, CSV, or an image such as a WhatsApp screenshot (read with OCR). Up to 15 MB.")
    if up is not None:
        source = (up.name, up.getvalue())
    elif pick:
        source = (SAMPLES[pick], (SAMPLE_DIR / SAMPLES[pick]).read_bytes())
        st.caption(f"Using the sample file **{SAMPLES[pick]}** (synthetic content). Upload your own file to check it instead.")
    else:
        source = None
    mode = st.segmented_control("Checks to run", list(MODES), format_func=MODES.get, default=AnalysisMode.FULL, key="file_mode", required=True)
    b1, _ = st.columns([1, 3])
    go = b1.button("Check file", type="primary", icon=":material/upload_file:", width="stretch", disabled=source is None)
    if not ocr_available():
        st.caption("OCR is not installed, so images and scanned PDF pages can't be read. Install Tesseract to enable it (see the README).")
    else:
        st.caption("Images and scanned PDF pages are read with OCR; check the warnings on the result for pages that could not be read.")

if go and source is not None:
    name, data = source
    with st.spinner(f"Reading {name} and analysing its content..."):
        try:
            st.session_state.file_result = client().scan_file(name, data, mode or AnalysisMode.FULL)
        except ClientError as exc:
            st.error(str(exc), icon=":material/error:")

res = st.session_state.get("file_result")
if res:
    st.space("small")
    results.render(res.result, res.original_text, key="file", client=client())
